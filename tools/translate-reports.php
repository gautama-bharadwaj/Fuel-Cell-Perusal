<?php
/*
 * Builds js/reports.js from the original FPDF report scripts.
 *
 * The PDF reports were PHP scripts using FPDF. Their code is a small, regular
 * subset of PHP (FPDF calls, variables, arrays and for loops), so instead of
 * rewriting each report by hand this script translates the original PHP into
 * JavaScript token by token. js/fpdf.js then provides the same FPDF methods
 * on top of jsPDF, so the browser draws the same report.
 *
 * Usage (from the repository root, with the PHP sources from the
 * php-original branch checked out in a folder):
 *   git worktree add ../fcp-php php-original
 *   php tools/translate-reports.php ../fcp-php > js/reports.js
 */

$src = rtrim($argv[1], '/');
// report script => [results page it belongs to, model key]
$reports = [
  'pdfermodel1.php'            => ['model1.php', 'model1'],
  'pdfer.php'                  => ['model2.php', 'model2'],
  'Archives/v1.0.1.report.php' => ['Archives/v1.0.1.php', 'v1.0.1'],
  'Archives/v1.1.1.report.php' => ['Archives/v1.1.1.php', 'v1.1.1'],
  'Archives/v2.0.1.report.php' => ['Archives/v2.0.1.php', 'v2.0.1'],
  'Archives/v2.1.1.report.php' => ['Archives/v2.1.1.php', 'v2.1.1'],
  'Archives/v2.2.1.report.php' => ['Archives/v2.2.1.php', 'v2.2.1'],
];

function translate($code) {
  $out = '';
  $tokens = token_get_all($code);
  $parens = [];        // stack: true when the "(" opened an array(...)
  $braces = [];        // stack of what each "{" opened: 'class' | 'block'
  $skipToSemicolon = false;
  $n = count($tokens);
  for ($k = 0; $k < $n; $k++) {
    $t = $tokens[$k];
    $id = is_array($t) ? $t[0] : null;
    $text = is_array($t) ? $t[1] : $t;
    if ($skipToSemicolon) { if ($text === ';') $skipToSemicolon = false; continue; }
    switch (true) {
      case $id === T_OPEN_TAG || $id === T_CLOSE_TAG || $id === T_INLINE_HTML:
      case $id === T_COMMENT || $id === T_DOC_COMMENT:
        $out .= ($id === T_COMMENT || $id === T_DOC_COMMENT) ? '' : "\n";
        break;
      case $id === T_REQUIRE || $id === T_REQUIRE_ONCE || $id === T_INCLUDE:
        $skipToSemicolon = true;
        break;
      case $id === T_CLASS:
        // class PDF extends FPDF { ... }  => methods become pdf.Header = function () {...}
        while ($tokens[$k] !== '{') $k++;
        $braces[] = 'class';
        break;
      case $id === T_FUNCTION:
        $k++; while (is_array($tokens[$k]) && $tokens[$k][0] === T_WHITESPACE) $k++;
        $out .= 'pdf.' . $tokens[$k][1] . ' = function ';
        break;
      case $text === '{':
        $braces[] = 'block'; $out .= '{';
        break;
      case $text === '}':
        $b = array_pop($braces);
        if ($b !== 'class') $out .= '}';
        break;
      case $id === T_VARIABLE:
        $name = substr($text, 1);
        if ($name === 'pdf' || $name === 'this') {
          // "$pdf = new PDF();" is done by the caller
          $j = $k + 1; while (is_array($tokens[$j]) && $tokens[$j][0] === T_WHITESPACE) $j++;
          if ($tokens[$j] === '=') { $skipToSemicolon = true; break; }
          $out .= 'pdf';
        } elseif ($name === '_POST') $out .= 'POST';
        elseif ($name === '_SESSION') $out .= 'SESSION';
        else $out .= 'V.' . $name;
        break;
      case $id === T_OBJECT_OPERATOR:
        $out .= '.';
        break;
      case $id === T_ARRAY:
        $k++; while (is_array($tokens[$k]) && $tokens[$k][0] === T_WHITESPACE) $k++;
        $parens[] = true; $out .= '[';
        break;
      case $text === '(':
        $parens[] = false; $out .= '(';
        break;
      case $text === ')':
        $out .= array_pop($parens) ? ']' : ')';
        break;
      case $text === '.':
        $out .= ' + ';   // string concatenation
        break;
      case $id === T_STRING && in_array($text, ['session_start']):
        $skipToSemicolon = true;
        break;
      case $id === T_STRING && in_array($text, ['date', 'time']):
        $out .= 'php_' . $text;
        break;
      case $id === T_CONSTANT_ENCAPSED_STRING:
        if ($text[0] === '"') { $out .= json_encode(stripcslashes(substr($text, 1, -1))); break; }
        $out .= $text;
        break;
      default:
        $out .= $text;
    }
  }
  return $out;
}

// $_SESSION['key'] = $var; on the results page tells us which result variable each key holds
function sessionMap($code) {
  preg_match_all('/\$_SESSION\[\s*[\'"](\w+)[\'"]\s*\]\s*=\s*\$(\w+)\s*;/', $code, $m, PREG_SET_ORDER);
  $map = [];
  foreach ($m as $x) $map[$x[1]] = $x[2];
  return $map;
}

echo "/*\n * Fuel Cell Perusal - PDF reports.\n *\n";
echo " * GENERATED by tools/translate-reports.php from the original FPDF report scripts\n";
echo " * (pdfer.php, pdfermodel1.php, Archives/*.report.php on the php-original branch).\n";
echo " * Do not edit by hand.\n */\n";
echo "(function () {\n'use strict';\nwindow.FCPReports = {};\n";
foreach ($reports as $report => [$page, $key]) {
  $js = translate(file_get_contents("$src/$report"));
  $js = preg_replace("/\n\s*\n+/", "\n", $js);
  $map = sessionMap(file_get_contents("$src/$page"));
  echo "\n// ---- $report\n";
  echo "window.FCPReports[" . json_encode($key) . "] = {\n";
  echo "  session: " . json_encode($map) . ",\n";
  echo "  run: function (pdf, POST, SESSION, php_date, php_time) {\n  var V = {};\n";
  echo $js . "\n  }\n};\n";
}
echo "})();\n";
